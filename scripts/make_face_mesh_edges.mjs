// Writes packages/shared/src/face_mesh_edges.ts: the edges of MediaPipe's 468-point face mesh
// (FaceLandmarker.FACE_LANDMARKS_TESSELATION, Apache-2.0), so apps can draw dots along the mesh
// without loading MediaPipe. Run again only if MediaPipe changes its mesh: node scripts/make_face_mesh_edges.mjs
import { writeFileSync } from 'node:fs';
const { FaceLandmarker } = await import('@mediapipe/tasks-vision');
const seen = new Set();
const flat = [];
for (const { start, end } of FaceLandmarker.FACE_LANDMARKS_TESSELATION) {
  const key = start < end ? `${start}-${end}` : `${end}-${start}`;
  if (seen.has(key)) continue;
  seen.add(key);
  flat.push(start, end);
}
const body = `// Generated by scripts/make_face_mesh_edges.mjs from MediaPipe FaceLandmarker.FACE_LANDMARKS_TESSELATION
// (https://github.com/google-ai-edge/mediapipe, Apache-2.0). ${flat.length / 2} unique edges of the 468-point face mesh.
// Pairs of landmark indices: [a0, b0, a1, b1, ...].
export const FACE_MESH_EDGES = new Uint16Array([${flat.join(',')}]);
`;
writeFileSync('packages/shared/src/face_mesh_edges.ts', body);
console.log('edges', flat.length / 2);
